const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const file = path.join(__dirname, '../prototypes/interest-explorer/flow.js');
assert.ok(fs.existsSync(file), '一次一題流程尚未實作');
const { createSession } = require(file);
const session = createSession();
assert.equal(session.index, 0);
assert.equal(session.answered, 0);
assert.equal(session.next(), 'missing');
assert.equal(session.index, 0);
assert.equal(session.back(), false);
for (const invalid of [-1,5,1.5,null,'3',undefined]) assert.throws(() => session.choose(invalid), /回答/);
session.choose(0);
assert.equal(session.answered, 1);
assert.equal(session.next(), 'next');
assert.equal(session.index, 1);
assert.equal(session.next(), 'missing');
assert.equal(session.back(), true);
assert.equal(session.answers[0], 0);
session.choose(4);
assert.equal(session.answered, 1);
session.answers[0] = 99;
assert.equal(session.answers[0], 4, '外部讀取不應修改會話');
assert.equal(session.next(), 'next');
for (let index=1;index<30;index++) {
  assert.equal(session.index,index);
  session.choose(index%5);
  assert.equal(session.next(), index===29 ? 'complete':'next');
}
assert.equal(session.answered,30);
assert.equal(session.index,29);
assert.equal(session.next(),'complete');
session.first();
assert.equal(session.index,0);
assert.equal(session.answered,30);
assert.equal(session.answers[0],4);
session.reset();
assert.equal(session.index,0);
assert.equal(session.answered,0);
assert.ok(session.answers.every(value=>value===null));
console.log('Interest flow: single-question navigation, required choice, zero score, back/edit, immutable snapshots, completion and reset passed.');
