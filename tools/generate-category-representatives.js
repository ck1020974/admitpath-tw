function splitSchoolDepartmentName(value) {
  const text = String(value || "").trim();
  const match = text.match(/^(.+?(?:大學|學院))(.*)$/);
  if (!match) return { schoolName: "", departmentName: text };
  return {
    schoolName: match[1].trim(),
    departmentName: match[2].trim(),
  };
}

const categoryMap = new Map();
rows.forEach((row) => {
  if (row.groupName === "跨領域") return;
  if (!categoryMap.has(row.categoryName)) {
    categoryMap.set(row.categoryName, {
      groupName: row.groupName,
      schools: new Map(),
    });
  }
  const entry = categoryMap.get(row.categoryName);
  const { schoolName, departmentName } = splitSchoolDepartmentName(row.schoolDepartmentName);
  if (!schoolName) return;
  if (!entry.schools.has(schoolName)) {
    entry.schools.set(schoolName, []);
  }
  if (departmentName && !entry.schools.get(schoolName).includes(departmentName)) {
    entry.schools.get(schoolName).push(departmentName);
  }
});

const output = {};

[...categoryMap.entries()]
  .sort((a, b) => a[0].localeCompare(b[0], "zh-Hant"))
  .forEach(([categoryName, entry]) => {
    const availableSchools = [...entry.schools.keys()];
    const preferred = [...new Set([
      ...(CATEGORY_OVERRIDES[categoryName] || []),
      ...(GROUP_BOOST[entry.groupName] || []),
      ...GENERAL_SCHOOL_PRIORITY,
    ])];

    const deptCount = (school) => (entry.schools.get(school) || []).length;
    const prioritySchools = availableSchools
      .slice()
      .sort((a, b) => {
        const ai = preferred.indexOf(a);
        const bi = preferred.indexOf(b);
        const ar = ai === -1 ? 9999 : ai;
        const br = bi === -1 ? 9999 : bi;
        if (ar !== br) return ar - br;
        const deptDiff = deptCount(b) - deptCount(a);
        if (deptDiff !== 0) return deptDiff;
        return a.localeCompare(b, "zh-Hant");
      })
      .slice(0, 8);

    output[categoryName] = {
      groupName: entry.groupName,
      prioritySchools,
    };
  });

fs.writeFileSync(outputPath, `${JSON.stringify(output, null, 2)}\n`, "utf8");
console.log(`Wrote ${Object.keys(output).length} category representative entries to ${outputPath}`);
