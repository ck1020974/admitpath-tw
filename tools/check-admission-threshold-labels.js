const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const AdmissionRules = require('../site/admission-rules.js');
const standards = JSON.parse(fs.readFileSync(path.join(root, 'site/data/ceec_gsat_five_standard_scores.json'), 'utf8'));
const records = JSON.parse(fs.readFileSync(path.join(root, 'site/data/admissions_records.json'), 'utf8'));
const record = records.find(r => r.year === 115 && r.programCode === '001012' && r.channelKey === 'personal_application');
const rules = AdmissionRules.thresholds(record, standards);
const either = rules.find(r => r.kind === 'any');
assert.ok(either);
assert.equal(AdmissionRules.check(either, {scores: {'數B': 5}}).status, 'match');
assert.equal(AdmissionRules.check(either, {scores: {'數A': 8}}).status, 'match');
assert.equal(AdmissionRules.check(either, {scores: {'數A': 7, '數B': 4}}).status, 'miss');
assert.equal(AdmissionRules.describe(rules.find(r => r.subjects[0] === '國文')), '國文 前標');
assert.equal(AdmissionRules.describe({kind: 'score', subjects:['國文'], threshold:15, source:'倍率篩選'}), '國文 ≥ 15級分');
const app = fs.readFileSync(path.join(root, 'site/app.js'), 'utf8');
const definition = app.match(/function applicationThresholdParts\([\s\S]*?\n\}/)[0];
const context = {AdmissionRules, state:{gsatStandards:standards}, record};
vm.createContext(context);
vm.runInContext(definition + '\nresult = applicationThresholdParts(record)', context);
const math = context.result.filter(p => /^數[AB]/.test(p.text));
assert.equal(math.length, 2);
assert.equal(math[0].text, '數A 均標（擇一）');
assert.equal(math[1].text, '數B 均標（擇一）');
console.log('Threshold label, separate math chips, OR evaluation, and numerical result checks passed.');
